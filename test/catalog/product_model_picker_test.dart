// test/catalog/product_model_picker_test.dart
//
// The model picker's two contracts that no other test can see.
//
//  1. PREVIEW IS NOT SELECT. Opening a model in the viewer and coming back must
//     leave the form exactly as it was — the selection, and every typed field.
//     If preview also selected, every comparison would change the answer, and
//     the user would have no way to look at a model without choosing it.
//
//  2. NO STAFF ROUTE, EVER. The owner list route and the staff one return
//     DIFFERENT payloads through different parsers, and an owner (or an admin
//     who does not own the capture) gets an identical 404 on `/admin`. Routing
//     around that would be the "second, weaker door" AGENTS.md forbids. This is
//     the contract that would break silently, so it is asserted at the WIRE:
//     the real repository runs over a fake Dio adapter that records every path.
