// test/projects/owner_models_routing_test.dart
//
// WHERE an owner's model taps land, now that a project can show more than one
// model:
//   • "Models" ALWAYS opens the list;
//   • "View" takes the shortcut only when there is nothing to choose between —
//     one openable model still opens directly, exactly as it did before this
//     screen existed;
//   • the count that decides comes from the MODELS ENDPOINT, not from the
//     card's `modelCount`. That is the regression these tests pin: one
//     generation that was optimized offers TWO openable builds while
//     `modelCount` — one per generation — says 1, so routing on the card's
//     count dropped the owner into whichever build happened to be served and
//     hid the other one entirely.
//
// Hermetic: fake notifier + fake repository, no network.
