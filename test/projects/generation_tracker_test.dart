// The app-scoped generation tracker: the state machine, the poll loop, the
// suppression seam that keeps it off ModelBuildingScreen's endpoint, and the
// capture-lock predicate derived from it.
//
// TIMER DISCIPLINE: the tracker is app-scoped and NOT autoDisposed, so any test
// that leaves it with a running entry leaves a pending cadence timer behind and
// fails with "A Timer is still pending". Every harness therefore registers
// `container.dispose` as a tear-down, which cancels both the cadence timer and
// any success-linger timer.
