/** One generation record by id, or null. */
export async function findProjectModelById(modelId: string): Promise<IProjectModel | null> {
  if (!Types.ObjectId.isValid(modelId)) return null;
  return ProjectModel.findById(new Types.ObjectId(modelId)).exec();
}

/** A project's full generation history, newest first (the staff compare view). */
export async function listProjectModels(projectId: string): Promise<IProjectModel[]> {
  const records = await ProjectModel.find({ projectId: new Types.ObjectId(projectId) })
    .sort({ createdAt: -1 })
    .exec();
  await backfillGlbBytes(records);
  return records;
}

/**
 * Fills in `artifacts.glbBytes` for records written before the field existed.
 *
 * Lazy and on the read path on purpose: the size is only ever needed to decide
 * whether to offer the Optimize button, and this is the one place that
 * question gets asked about a whole history at once. Every record is HEADed at
 * most once, ever — the value is written back.
 *
 * BEST-EFFORT IN BOTH DIRECTIONS. A HEAD that fails (or an object that has
 * gone) leaves the size UNKNOWN, which downstream reads as "no button" — never
 * as an error, because a staff user losing the whole model list over one S3
 * hiccup is far worse than a button that shows up on the next refresh. The
 * write-back is equally optional; the next list re-derives it.
 */
async function backfillGlbBytes(records: IProjectModel[]): Promise<void> {
  const pending = records.filter(
    (r) => r.status === 'SUCCEEDED' && r.artifacts?.glbKey && r.artifacts.glbBytes === undefined
  );
  if (pending.length === 0) return;

  await Promise.all(
    pending.map(async (record) => {
      try {
        const head = await headObject(BUCKET_ARTIFACTS, record.artifacts!.glbKey);
        if (head.outcome !== 'ok' || head.contentLength <= 0) return;
        // Mutate the in-memory record too, so THIS response already carries the
        // size rather than making the client refresh to see the button.
        record.artifacts!.glbBytes = head.contentLength;
        await ProjectModel.updateOne(
          { _id: record._id },
          { $set: { 'artifacts.glbBytes': head.contentLength } }
        ).exec();
      } catch {
        // Size stays unknown. See the doc comment.
      }
    })
  );
}

/**
 * The newest SUCCEEDED model for a project, or null.
 *
 * Filtered in the QUERY, not picked off the history list: a fresh regenerate
 * sits at the head of the history as QUEUED/PROCESSING, and "latest overall,
 * if it happens to be SUCCEEDED" would hide the good model the project already
 * has for the whole duration of the new run.
 *
 * BEHAVIOUR CHANGE (optimization): an OPT record is a SUCCEEDED record, so once
 * a model is optimized THIS returns the optimized one. That is the intent — the
 * owner should get the small file — and it is exactly why the optimization
 * processor COPIES the source's USDZ and preview onto the OPT record: without
 * them, the first optimization would silently kill AR Quick Look and the
 * project thumbnail.
 */
export async function latestSucceededModel(projectId: string): Promise<IProjectModel | null> {
  return ProjectModel.findOne({
    projectId: new Types.ObjectId(projectId),
    status: 'SUCCEEDED',
  })
    .sort({ createdAt: -1 })
    .exec();
}

/**
 * The newest SUCCEEDED model as the OWNER may see it — the only generation
 * surface the owner-facing project detail exposes.
 */
export async function latestOwnerModelFor(projectId: string): Promise<OwnerModelDto | null> {
  const record = await latestSucceededModel(projectId);
  if (!record) return null;
  // The owner's Optimize affordance needs the same child check the staff list
  // does — one extra small query, and the alternative is a button that 409s.
  const optimizedSourceIds = await optimizedSourceIdsFor(projectId);
  return toOwnerModelDto(record, optimizedSourceIds);
}

/**
 * The generation the owner is currently waiting on, or null.
 *
 * Returns the newest record that is NOT yet SUCCEEDED — QUEUED/PROCESSING while
 * it runs, and FAILED so the app can offer "try again" rather than silently
 * showing nothing after a failed automatic attempt.
 *
 * Paired with {@link latestOwnerModelFor}, never a replacement for it: while a
 * regenerate is in flight the owner keeps seeing the model they already have.
 *
 * OPTIMIZATION RECORDS ARE EXCLUDED. They are not generations: a running
 * optimization would otherwise put "creating your 3D model…" on the screen of
 * someone who already HAS their model and merely asked for a smaller copy of
 * it — and a failed one would offer "try again" for a generation that never
 * happened. The `source` filter, not the status one, is what keeps this
 * endpoint's meaning intact.
 */
export async function pendingOwnerGenerationFor(
  projectId: string
): Promise<OwnerGenerationDto | null> {
  const record = await ProjectModel.findOne({
    projectId: new Types.ObjectId(projectId),
    status: { $ne: 'SUCCEEDED' },
    source: { $ne: 'optimized' satisfies ModelSource },
  })
    .sort({ createdAt: -1 })
    .exec();
  if (!record) return null;

  return {
    id: record.id as string,
    status: record.status,
    isAutoGenerated: record.createdBySystem === true,
    // The worker's live sub-status, reduced to the one number an owner cares
    // about. The phase name stays staff-only.
    ...(record.progress ? { progressPercent: record.progress.percent } : {}),
    ...(record.error
      ? { error: { code: record.error.code, message: record.error.message } }
      : {}),
    createdAt: record.createdAt.toISOString(),
  };
}

// ── Approve ──────────────────────────────────────────────────────────────────

export type ApproveModelResult =
  | { outcome: 'MODEL_NOT_FOUND' }
  /** Only a SUCCEEDED record can be approved — there is nothing else to sign off. */
  | { outcome: 'NOT_APPROVABLE'; status: ModelStatus }
  | { outcome: 'APPROVED'; model: IProjectModel };

/**
 * The "we're satisfied with the Meshy result — no manual creation needed" gate.
 *
 * One conditional findOneAndUpdate fenced on status SUCCEEDED (the codebase's
 * no-transactions atomicity pattern), so it can never approve a record that
 * failed. Re-approving is idempotent: it re-stamps `approved` with the latest
 * actor rather than erroring, matching the rest of the admin surface's
 * double-tap tolerance.
 */
export async function approveModel(
  projectId: string,
  modelId: string,
  actor: ModelActor
): Promise<ApproveModelResult> {
  const updated = await ProjectModel.findOneAndUpdate(
    {
      _id: new Types.ObjectId(modelId),
      projectId: new Types.ObjectId(projectId),
      status: 'SUCCEEDED',
    },
    { $set: { approved: { at: new Date(), byUserId: new Types.ObjectId(actor.userId) } } },
    { new: true }
  ).exec();
  if (updated) return { outcome: 'APPROVED', model: updated };

  // The fenced write lost — distinguish "no such record" from "wrong status"
  // so the route can answer 404 vs 409. (Both are staff-only surfaces, so the
  // enumeration-safety rule that collapses these on owner routes doesn't apply.)
  const existing = await ProjectModel.findOne({
    _id: new Types.ObjectId(modelId),
    projectId: new Types.ObjectId(projectId),
  }).exec();
  if (!existing) return { outcome: 'MODEL_NOT_FOUND' };
  return { outcome: 'NOT_APPROVABLE', status: existing.status };
}

// ── Optimize ─────────────────────────────────────────────────────────────────

/** Why a model cannot be optimized — one stable code per rule in
 * {@link canOptimizeModel}, so the client can map each to its own copy. */
export type NotOptimizableReason =
  | 'NOT_SUCCEEDED'
  | 'NO_GLB'
  | 'SIZE_UNKNOWN'
  | 'BELOW_THRESHOLD'
  /**
   * A live OPT child already exists. Part of the vocabulary because it is one
   * of the six rules {@link canOptimizeModel} enforces, but
   * {@link requestModelOptimization} never returns it: a second request for a
   * model that already has one is a REPLAY (200 + the existing record), which
   * is more useful to the caller than a 409 telling them what they asked for
   * already happened.
   */
  | 'ALREADY_OPTIMIZED'
  | 'IS_OPTIMIZED';

export type RequestModelOptimizationResult =
  | { outcome: 'PROJECT_NOT_FOUND' }
  | { outcome: 'MODEL_NOT_FOUND' }
  | { outcome: 'NOT_OPTIMIZABLE'; reason: NotOptimizableReason }
  /**
   * An OPT record already existed — NOT re-enqueued. `sourceBytes` is the
   * SOURCE model's GLB size (known, since eligibility required it), carried on
   * both success outcomes so the route's analytics reports a real number
   * instead of approximating one from a record the worker has not filled in yet.
   */
  | { outcome: 'REPLAYED'; model: IProjectModel; sourceBytes: number }
  | { outcome: 'CREATED'; model: IProjectModel; sourceBytes: number };

/**
 * Creates the OPT record for [modelId] and enqueues the job that fills it in.
 *
 * THE SERVER IS THE AUTHORITY. The client's button visibility is a courtesy:
 * every condition {@link canOptimizeModel} checks is re-checked here against
 * fresh documents, and the unique partial index on `optimizedFrom` is what
 * actually makes "a model is optimized at most once" true — a concurrent double
 * tap has both requests pass the read checks, and the loser's E11000 resolves
 * to a REPLAY of the winner rather than a second record.
 *
 * Order mirrors the money contract in {@link createMeshyModelRequest}: insert
 * the record FIRST, enqueue the Job second. A crash in between leaves a QUEUED
 * record with no job — visible, and re-requestable — which is strictly better
 * than a job whose record does not exist. If the enqueue THROWS, the record is
 * flipped to FAILED so it cannot sit QUEUED forever.
 */
export async function requestModelOptimization(input: {
  projectId: string;
  modelId: string;
  actor: ModelActor;
}): Promise<RequestModelOptimizationResult> {
  const { projectId, modelId, actor } = input;

  const project = await Project.findOne({
    _id: new Types.ObjectId(projectId),
    deletedAt: null,
  }).exec();
  if (!project) return { outcome: 'PROJECT_NOT_FOUND' };

  if (!Types.ObjectId.isValid(modelId)) return { outcome: 'MODEL_NOT_FOUND' };
  const source = await ProjectModel.findOne({
    _id: new Types.ObjectId(modelId),
    projectId: project._id,
  }).exec();
  if (!source) return { outcome: 'MODEL_NOT_FOUND' };

  // Re-derived here rather than trusting canOptimizeModel's boolean, because
  // the ROUTE needs to say WHICH rule refused — a bare "409" on a button the
  // client just rendered is unexplainable to the person who tapped it.
  const reason = notOptimizableReasonFor(source);
  if (reason) return { outcome: 'NOT_OPTIMIZABLE', reason };
  // Guaranteed present: SIZE_UNKNOWN is one of the rules above.
  const sourceBytes = source.artifacts!.glbBytes!;

  const existing = await ProjectModel.findOne({ optimizedFrom: source._id }).exec();
  if (existing) {
    // A FAILED child does not block a retry — it is replaced, not replayed, so
    // one transient failure cannot permanently consume the single slot the
    // unique index allows.
    if (existing.status !== 'FAILED') {
      return { outcome: 'REPLAYED', model: existing, sourceBytes };
    }
    await ProjectModel.deleteOne({ _id: existing._id }).exec();
  }

  let record: IProjectModel;
  try {
    record = await ProjectModel.create({
      projectId: project._id,
      // The CAPTURE job, inherited from the source: the artifact key space is
      // anchored to its rawPrefix, so the OPT output lands beside the
      // generation it came from.
      jobId: source.jobId,
      source: 'optimized' satisfies ModelSource,
      status: 'QUEUED',
      // Nothing was selected — this is a derivative of one model, not of any
      // photos. An empty array is the honest answer, and every reader already
      // handles it (the history row simply prints no photo count).
      selectedKeys: [],
      optimizedFrom: source._id,
      createdByUserId: new Types.ObjectId(actor.userId),
      createdByRole: actor.role,
      // Neither createdBySystem nor createdByManualButton: optimization is not
      // a server-selected GENERATION and must never consume the 24h spend
      // ceiling that countServerSelectedGenerationsInLast24h enforces.
    });
  } catch (err: unknown) {
    if (isDuplicateKeyError(err)) {
      const winner = await ProjectModel.findOne({ optimizedFrom: source._id }).exec();
      // The index guarantees a winner exists; if it somehow does not, rethrow
      // rather than silently doing nothing.
      if (winner) return { outcome: 'REPLAYED', model: winner, sourceBytes };
    }
    throw err;
  }

  try {
    await Job.create({
      projectId: project._id,
      userId: project.userId,
      jobType: MODEL_OPTIMIZATION_JOB_TYPE,
      state: 'QUEUED',
      payload: { modelId: record.id as string },
    });
  } catch (err: unknown) {
    record.status = 'FAILED';
    record.error = { code: 'ENQUEUE_FAILED', message: 'Could not enqueue the optimization job.' };
    await record.save();
    throw err;
  }

  return { outcome: 'CREATED', model: record, sourceBytes };
}

/**
 * The first rule {@link canOptimizeModel} would fail on, or null if none do.
 *
 * Deliberately ordered most-fundamental first, so the reason a caller gets is
 * the most useful one: "this hasn't finished generating" beats "its size is
 * unknown" for a record that is still PROCESSING.
 *
 * Note this does NOT check for an existing OPT child — that is a separate
 * lookup in the caller, because it is also where the FAILED-child retry is
 * decided.
 */
function notOptimizableReasonFor(record: IProjectModel): NotOptimizableReason | null {
  if (record.source === 'optimized') return 'IS_OPTIMIZED';
  if (record.status !== 'SUCCEEDED') return 'NOT_SUCCEEDED';
  if (!record.artifacts?.glbKey) return 'NO_GLB';
  if (record.artifacts.glbBytes === undefined) return 'SIZE_UNKNOWN';
  if (record.artifacts.glbBytes <= env.MODEL_OPTIMIZE_THRESHOLD_BYTES) return 'BELOW_THRESHOLD';
  return null;
}

