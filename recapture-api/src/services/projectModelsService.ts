/**
 * Meshy Multi-Image to 3D accepts 1–4 images. We require a MINIMUM of 3: with
 * fewer views the generative model hallucinates most of the object, and the
 * result is not worth a paid generation. Enforced identically on the client
 * (the Create Model CTA) — this is the authority.
 */
export const MIN_SELECTED_PHOTOS = 3;
export const MAX_SELECTED_PHOTOS = 4;

/** The staff actor requesting or approving a generation. */
export interface ModelActor {
  userId: string;
  role: UserRole;
}

// ── DTOs ─────────────────────────────────────────────────────────────────────

/** Staff-facing model record. Ids are exposed as `id`, never `_id`. */
export interface ProjectModelDto {
  id: string;
  projectId: string;
  jobId: string;
  source: ModelSource;
  status: ModelStatus;
  selectedKeys: string[];
  /**
   * Live worker sub-status for a PROCESSING record — drives the staff progress
   * UI ("Generating 3D model · 45%"). Absent on terminal records and on records
   * written before this field existed, so clients must treat it as optional.
   */
  progress?: { phase: ModelProgressPhase; percent: number };
  artifacts?: { glb: string; usdz?: string; preview?: string };
  approved?: { at: string };
  error?: { code: string; message: string };
  /**
   * How this generation was DECIDED — the synchronous request steps and the
   * photo selector's counters. Absent on every record written before the trace
   * existed, so clients must default it to nothing.
   *
   * STAFF-ONLY: it names our S3 key layout and our pipeline internals. It is on
   * this DTO and deliberately on NEITHER owner DTO.
   */
  generationTrace?: ModelGenerationTrace;
  /**
   * Size of the GLB in bytes, when known. ABSENT MEANS UNKNOWN, NOT SMALL —
   * records predating the field have none until the list backfills them, and a
   * client must render "size unknown", never "0 B".
   */
  glbBytes?: number;
  /** Set on an OPT record: the model it was derived from. */
  optimizedFromId?: string;
  /** Set on an OPT record: what the pass achieved, for the "−68%" label. */
  optimization?: { sourceBytes: number; outputBytes: number };
  /**
   * THE SERVER'S OWN VERDICT on whether the Optimize button belongs on this
   * row. Shipped as a boolean rather than shipping the threshold, because the
   * moment the client re-implements the rule the two can disagree — and the
   * disagreement is invisible until someone taps a button the server refuses.
   * See {@link canOptimizeModel} for the rule itself.
   */
  canOptimize: boolean;
  createdAt: string;
  updatedAt: string;
}

/**
 * OWNER-facing model. Deliberately smaller than the staff DTO: the URL, the
 * origin flag that drives the "Created by Meshy AI" badge, and whether it is
 * approved — nothing else. No S3 keys, no selectedKeys, no staff actor ids, no
 * meshyTaskId: an owner must not learn our key layout or who curated their
 * project.
 */
export interface OwnerModelDto {
  id: string;
  source: ModelSource;
  glbUrl: string;
  usdzUrl?: string;
  previewUrl?: string;
  approved: boolean;
  /**
   * True when the worker generated this itself after the capture finished,
   * with no human in the loop. Drives the "AI generated — preview quality"
   * badge and the regenerate affordance: an auto-generated model is shown as a
   * preview, not as a finished, signed-off product.
   */
  isAutoGenerated: boolean;
  /**
   * GLB size in bytes when known — absent means UNKNOWN. Named `sizeBytes`
   * rather than `glbBytes`: an owner is told how big their download is, not
   * which of our artifacts it happens to be.
   */
  sizeBytes?: number;
  /** True when this model IS the optimized derivative of another one. */
  isOptimized: boolean;
  /** The server's verdict on the owner-facing Optimize action. */
  canOptimize: boolean;
  createdAt: string;
}

/**
 * One row of the OWNER-facing model list (`GET /projects/:id/models`).
 *
 * A superset of {@link OwnerModelDto} in exactly two respects, and a subset of
 * the staff DTO in every other:
 *
 *  • `status` is present, and `glbUrl` is OPTIONAL as a direct consequence.
 *    {@link OwnerModelDto} describes the one finished model behind
 *    `GET /projects/:id`, so it can promise a URL. A LIST cannot: the row the
 *    owner most needs to see right after tapping Optimize is the QUEUED one,
 *    which has no artifacts yet. Dropping unfinished records would make the
 *    action look like it did nothing.
 *  • `progressPercent` and `error` are carried in the SAME owner-safe shapes
 *    {@link OwnerGenerationDto} already ships — a bare number (never a phase
 *    name, which describes our pipeline internals) and mapped failure copy.
 *
 * Everything staff-only stays out, and the omissions are the point: no
 * `selectedKeys`, no `generationTrace`, no `jobId`/`projectId`, no
 * `optimizedFromId` (it names a record the owner cannot address), no
 * `optimization` before/after byte counts, no actor ids, no S3 keys.
 */
export interface OwnerModelListItemDto {
  id: string;
  source: ModelSource;
  status: ModelStatus;
  /** Present only once the record has artifacts — i.e. once it SUCCEEDED. */
  glbUrl?: string;
  usdzUrl?: string;
  previewUrl?: string;
  approved: boolean;
  isAutoGenerated: boolean;
  sizeBytes?: number;
  isOptimized: boolean;
  canOptimize: boolean;
  /** Coarse 0–100 while pending, when the worker has reported any. */
  progressPercent?: number;
  /** Owner-safe failure copy — mapped codes only, never raw upstream text. */
  error?: { code: string; message: string };
  createdAt: string;
}

/**
 * A generation the owner is currently WAITING on — the state that only exists
 * because generation can now start without anyone asking for it.
 *
 * Deliberately separate from {@link OwnerModelDto}: a project can have a good
 * model AND a newer generation in flight at the same time, and the owner must
 * keep seeing the former while the latter runs.
 */
export interface OwnerGenerationDto {
  id: string;
  status: ModelStatus;
  /** True when the worker started this itself after a capture finished. */
  isAutoGenerated: boolean;
  /**
   * Coarse progress 0–100 from the worker's live `progress` sub-doc, when it
   * has reported any. The owner sees only the NUMBER, never the phase name —
   * "PREPARING"/"FINALIZING" describe our pipeline internals and mean nothing
   * to someone who just wants to know how long they are waiting.
   */
  progressPercent?: number;
  /** Owner-safe failure copy — mapped codes only, never raw upstream text. */
  error?: { code: string; message: string };
  createdAt: string;
}

// ── Optimization eligibility ─────────────────────────────────────────────────

/**
 * Which models in a project ALREADY have an optimized derivative, as a set of
 * source model ids.
 *
 * "Already" means an OPT child that is QUEUED, PROCESSING or SUCCEEDED —
 * PRESENT AND NOT BROKEN. A FAILED child is deliberately NOT counted, so one
 * transient S3 blip cannot permanently remove the only way to optimize a model.
 * (Judgment call, flagged in the PR: it is a deliberate reading of "if opt is
 * present, remove the button".)
 *
 * One query for the whole list — the alternative is N+1 across a history that
 * a busy project fills with a dozen attempts.
 */
export async function optimizedSourceIdsFor(projectId: string): Promise<Set<string>> {
  const rows = await ProjectModel.find(
    {
      projectId: new Types.ObjectId(projectId),
      optimizedFrom: { $exists: true },
      status: { $in: ['QUEUED', 'PROCESSING', 'SUCCEEDED'] },
    },
    { optimizedFrom: 1 }
  ).exec();
  return new Set(rows.map((r) => r.optimizedFrom!.toHexString()));
}

/**
 * Is this model worth (and legal to) optimize?
 *
 * True iff ALL of:
 *   • it SUCCEEDED — there is nothing to shrink otherwise;
 *   • it has a GLB;
 *   • its size is KNOWN — an unknown size is not a small one, and rendering the
 *     button on a guess means offering an action the server will refuse;
 *   • that size is above MODEL_OPTIMIZE_THRESHOLD_BYTES;
 *   • it is not ITSELF an optimized record — optimizing an optimization is
 *     recursion with no product;
 *   • it has no live OPT child (see {@link optimizedSourceIdsFor}).
 *
 * [optimizedSourceIds] omitted means "the caller did not look" — and this then
 * FAILS CLOSED to false. Every surface that must show the button passes it; the
 * ones that don't are returning a record that was just created (QUEUED, so
 * false regardless), and a fail-closed default can only ever hide a button, not
 * offer one the server would reject.
 */
export function canOptimizeModel(
  record: IProjectModel,
  optimizedSourceIds?: ReadonlySet<string>
): boolean {
  if (!optimizedSourceIds) return false;
  if (record.status !== 'SUCCEEDED') return false;
  if (record.source === 'optimized') return false;
  if (!record.artifacts?.glbKey) return false;
  const bytes = record.artifacts.glbBytes;
  if (bytes === undefined) return false;
  if (bytes <= env.MODEL_OPTIMIZE_THRESHOLD_BYTES) return false;
  return !optimizedSourceIds.has(record.id as string);
}

export function toProjectModelDto(
  record: IProjectModel,
  optimizedSourceIds?: ReadonlySet<string>
): ProjectModelDto {
  return {
    id: record.id as string,
    projectId: record.projectId.toHexString(),
    jobId: record.jobId.toHexString(),
    source: record.source,
    status: record.status,
    selectedKeys: record.selectedKeys,
    // Only meaningful while pending: a terminal record's progress is cleared by
    // the worker, and clients ignore it for terminal statuses regardless.
    ...(record.progress
      ? { progress: { phase: record.progress.phase, percent: record.progress.percent } }
      : {}),
    // Only our CloudFront URLs ever leave this service — never an S3 key and
    // never a (long-expired) Meshy URL.
    ...(record.artifacts
      ? {
          artifacts: {
            glb: record.artifacts.cdnUrls.glb,
            ...(record.artifacts.cdnUrls.usdz ? { usdz: record.artifacts.cdnUrls.usdz } : {}),
            ...(record.artifacts.cdnUrls.preview
              ? { preview: record.artifacts.cdnUrls.preview }
              : {}),
          },
        }
      : {}),
    ...(record.approved ? { approved: { at: record.approved.at.toISOString() } } : {}),
    ...(record.error ? { error: { code: record.error.code, message: record.error.message } } : {}),
    // Mongoose hands back a sub-document; flatten it so the wire payload is
    // plain JSON and no internal document machinery leaks into the response.
    ...(record.generationTrace
      ? {
          generationTrace: {
            steps: record.generationTrace.steps.map((s) => ({
              step: s.step,
              status: s.status,
              ...(s.detail ? { detail: s.detail } : {}),
              at: s.at,
              durationMs: s.durationMs,
            })),
            ...(record.generationTrace.selection
              ? { selection: record.generationTrace.selection }
              : {}),
            requestedBy: record.generationTrace.requestedBy,
          },
        }
      : {}),
    ...(record.artifacts?.glbBytes !== undefined ? { glbBytes: record.artifacts.glbBytes } : {}),
    ...(record.optimizedFrom ? { optimizedFromId: record.optimizedFrom.toHexString() } : {}),
    ...(record.optimization
      ? {
          optimization: {
            sourceBytes: record.optimization.sourceBytes,
            outputBytes: record.optimization.outputBytes,
          },
        }
      : {}),
    canOptimize: canOptimizeModel(record, optimizedSourceIds),
    createdAt: record.createdAt.toISOString(),
    updatedAt: record.updatedAt.toISOString(),
  };
}

/**
 * The owner projection. The optimization fields added here are deliberately
 * the SMALL ones: a size, two booleans. No `optimizedFrom` ObjectId (it names
 * another record the owner cannot address), no S3 keys, no staff actor ids —
 * the minimalism of this DTO is the feature.
 */
function toOwnerModelDto(
  record: IProjectModel,
  optimizedSourceIds?: ReadonlySet<string>
): OwnerModelDto | null {
  if (!record.artifacts) return null;
  return {
    id: record.id as string,
    source: record.source,
    glbUrl: record.artifacts.cdnUrls.glb,
    ...(record.artifacts.cdnUrls.usdz ? { usdzUrl: record.artifacts.cdnUrls.usdz } : {}),
    ...(record.artifacts.cdnUrls.preview ? { previewUrl: record.artifacts.cdnUrls.preview } : {}),
    approved: record.approved !== undefined,
    isAutoGenerated: record.createdBySystem === true,
    ...(record.artifacts.glbBytes !== undefined ? { sizeBytes: record.artifacts.glbBytes } : {}),
    isOptimized: record.source === 'optimized',
    canOptimize: canOptimizeModel(record, optimizedSourceIds),
    createdAt: record.createdAt.toISOString(),
  };
}

/**
 * The owner LIST projection. Built field-by-field rather than by spreading a
 * record: a spread is how a staff-only field silently reaches an owner the next
 * time the schema grows, and this DTO's whole value is what it leaves out.
 */
function toOwnerModelListItemDto(
  record: IProjectModel,
  optimizedSourceIds?: ReadonlySet<string>
): OwnerModelListItemDto {
  return {
    id: record.id as string,
    source: record.source,
    status: record.status,
    // Only our CloudFront URLs, and only when the record actually has them.
    ...(record.artifacts
      ? {
          glbUrl: record.artifacts.cdnUrls.glb,
          ...(record.artifacts.cdnUrls.usdz ? { usdzUrl: record.artifacts.cdnUrls.usdz } : {}),
          ...(record.artifacts.cdnUrls.preview
            ? { previewUrl: record.artifacts.cdnUrls.preview }
            : {}),
          ...(record.artifacts.glbBytes !== undefined
            ? { sizeBytes: record.artifacts.glbBytes }
            : {}),
        }
      : {}),
    approved: record.approved !== undefined,
    isAutoGenerated: record.createdBySystem === true,
    isOptimized: record.source === 'optimized',
    canOptimize: canOptimizeModel(record, optimizedSourceIds),
    // The NUMBER only — `progress.phase` stays staff-side on purpose.
    ...(record.progress ? { progressPercent: record.progress.percent } : {}),
    ...(record.error ? { error: { code: record.error.code, message: record.error.message } } : {}),
    createdAt: record.createdAt.toISOString(),
  };
}

/**
 * A project's model history as the OWNER may see it, newest first.
 *
 * Same ordering and same records as {@link listProjectModels} — including
 * pending and FAILED ones, so the row the owner just created by tapping
 * Optimize is visible while it runs and explains itself if it breaks. The
 * difference is entirely in the projection.
 *
 * Takes a projectId that the CALLER has already proven the owner owns; this
 * function does no authorization of its own, exactly like the staff list.
 */
export async function listOwnerProjectModels(
  projectId: string
): Promise<OwnerModelListItemDto[]> {
  const records = await listProjectModels(projectId);
  // One query for the whole list, same as the staff surface — without it every
  // row's canOptimize would fail closed and the action would never appear.
  const optimizedSourceIds = await optimizedSourceIdsFor(projectId);
  return records.map((r) => toOwnerModelListItemDto(r, optimizedSourceIds));
}

// ── Create ───────────────────────────────────────────────────────────────────

export interface CreateMeshyModelRequestInput {
  projectId: string;
  /** RELATIVE export-manifest keys, exactly as the Preview gallery holds them. */
  keys: string[];
  actor: ModelActor;
  /**
   * `Idempotency-Key` header, when the client sent one. The automatic path
   * supplies a DERIVED key (`auto:{jobId}`) instead of a client-supplied one,
   * which is what makes a re-run of a capture job replay rather than pay twice.
   */
  idempotencyKey?: string;
  /** True when the worker started this itself (no human asked). */
  createdBySystem?: boolean;
  /**
   * True when a person pressed "Generate 3D model" and the SERVER selected the
   * photos. Distinct from `createdBySystem` (a human DID ask) and from a plain
   * staff request (a human picked the photos by hand) — it is what lets the
   * shared 24h ceiling count automatic and button-triggered spends together
   * while leaving hand-curated staff selections to their own rate window.
   */
  createdByManualButton?: boolean;
  /**
   * The capture job these keys came from, PINNING the generation to it.
   *
   * Omit it and the newest exportable job is resolved instead — which is what
   * the staff surfaces want, because a human is curating the project's current
   * state at request time. The AUTOMATIC path must always supply it: it is
   * acting on one specific job, and a project that gains a newer finalized
   * capture mid-flight would otherwise have these keys presigned under the
   * wrong prefix (see findExportableJobById).
   */
  jobId?: Types.ObjectId | string;
}

export type CreateMeshyModelResult =
  | { outcome: 'PROJECT_NOT_FOUND' }
  | { outcome: 'NOT_EXPORTABLE' }
  /** Selection size outside [MIN_SELECTED_PHOTOS, MAX_SELECTED_PHOTOS] AFTER dedupe. */
  | { outcome: 'INVALID_COUNT'; count: number }
  /** A key escapes the job prefix — the whole request is refused. */
  | { outcome: 'INVALID_KEY'; key: string }
  /** A record already existed for this (actor, Idempotency-Key) — NOT re-enqueued. */
  | { outcome: 'REPLAYED'; model: IProjectModel }
  | { outcome: 'CREATED'; model: IProjectModel };

/**
 * Validates a staff photo selection and enqueues one Meshy generation.
 *
 * Order matters for the money contract: the ProjectModel record is inserted
 * FIRST (the unique (actor, Idempotency-Key) index is the race authority — a
 * double-tap loses here with E11000 and replays the winner instead of paying
 * twice), and only then is the worker job enqueued. A crash between the two
 * leaves a QUEUED record with no job — visible and re-requestable — which is
 * strictly better than a job whose record does not exist yet.
 *
 * The keys are resolved against an exportable job — the caller's own when it
 * passes [CreateMeshyModelRequestInput.jobId], otherwise the same newest-job
 * rule the export and soft-delete paths use — and validated with the SAME
 * containment rule, so a caller can only ever select photos it can already see.
 */
/**
 * The idempotency key that makes a capture's FIRST server-selected generation
 * unique — SHARED by both the automatic capture-processor path
 * (`maybeAutoGenerateModel`) and the non-forced owner "Generate 3D model" button
 * (`generateModelOnDemand`). Because both attribute the record to the same owner
 * and use this same key, whichever trigger fires first wins, and the other
 * collides on the unique `(createdByUserId, idempotencyKey)` index and REPLAYS
 * the existing record instead of paying for a SECOND Meshy task. That is what
 * stops one capture becoming two models (two charges, two different meshes).
 *
 * Derived from the capture jobId (not random, not the project) so a genuine
 * recapture — a new job id — correctly earns its own deliberate generation. A
 * forced staff regenerate appends a random suffix (see
 * `manualGenerationIdempotencyKey`) so it does NOT collide.
 */
export function captureGenerationIdempotencyKey(jobId: Types.ObjectId | string): string {
  return `capture:${jobId.toString()}`;
}

export async function createMeshyModelRequest(
  input: CreateMeshyModelRequestInput
): Promise<CreateMeshyModelResult> {
  const { projectId, actor, idempotencyKey } = input;

  const project = await Project.findOne({
    _id: new Types.ObjectId(projectId),
    deletedAt: null,
  }).exec();
  if (!project) return { outcome: 'PROJECT_NOT_FOUND' };

  // An explicit jobId pins the generation to the caller's OWN job; without one
  // the newest exportable job is resolved, unchanged, for the staff path.
  // Only the EXPLICIT-jobId branch was widened, to
  // findModelSourceJobById — which matches an exportable CAPTURE job OR an
  // UPLOADED photo-upload job. The no-jobId branch is untouched, so the staff
  // "newest exportable capture" rule is exactly what it always was and export /
  // preview / soft-delete keep ignoring PHOTO_UPLOAD jobs entirely.
  const job = input.jobId
    ? await findModelSourceJobById(projectId, input.jobId)
    : await findExportableJob(projectId);
  if (!job || !job.upload) return { outcome: 'NOT_EXPORTABLE' };

  // Dedupe before counting: selecting the same photo twice is a 2-photo
  // selection, and sending Meshy a duplicate image wastes a view slot.
  const keys = [...new Set(input.keys)];
  if (keys.length < MIN_SELECTED_PHOTOS || keys.length > MAX_SELECTED_PHOTOS) {
    return { outcome: 'INVALID_COUNT', count: keys.length };
  }
  for (const key of keys) {
    if (!isContainedRelativeKey(key)) return { outcome: 'INVALID_KEY', key };
  }

  let record: IProjectModel;
  try {
    record = await ProjectModel.create({
      projectId: project._id,
      jobId: job._id,
      source: 'meshy' satisfies ModelSource,
      status: 'QUEUED',
      selectedKeys: keys,
      createdByUserId: new Types.ObjectId(actor.userId),
      createdByRole: actor.role,
      ...(input.createdBySystem ? { createdBySystem: true } : {}),
      ...(input.createdByManualButton ? { createdByManualButton: true } : {}),
      ...(idempotencyKey ? { idempotencyKey } : {}),
    });
  } catch (err: unknown) {
    if (isDuplicateKeyError(err) && idempotencyKey) {
      const existing = await ProjectModel.findOne({
        createdByUserId: new Types.ObjectId(actor.userId),
        idempotencyKey,
      }).exec();
      // The index guarantees the winner exists; if it somehow does not, fall
      // through and rethrow rather than silently paying for a second run.
      if (existing) return { outcome: 'REPLAYED', model: existing };
    }
    throw err;
  }

  try {
    await Job.create({
      projectId: project._id,
      userId: job.userId,
      jobType: MESHY_MODEL_GENERATION_JOB_TYPE,
      // The enqueue itself: the worker claims `state: 'QUEUED'` documents.
      state: 'QUEUED',
      payload: { modelId: record.id as string },
    });
  } catch (err: unknown) {
    // No job means nothing will ever run — fail the record now so it does not
    // sit QUEUED forever and the staff user gets a real error to retry from.
    record.status = 'FAILED';
    record.error = { code: 'ENQUEUE_FAILED', message: 'Could not enqueue the generation job.' };
    await record.save();
    throw err;
  }

  return { outcome: 'CREATED', model: record };
}

/**
 * How many SERVER-SELECTED generations one actor has accrued in the rolling 24h
 * window — automatic and "Generate 3D model" button presses counted together.
 *
 * ONE pool on purpose: it is the same money, and a per-source cap would just be
 * two ways to spend twice as much. Hand-curated staff selections are excluded —
 * those already have their own rate window, and a human choosing the photos is
 * a different risk from the selector choosing them unattended.
 */
export async function countServerSelectedGenerationsInLast24h(userId: string): Promise<number> {
  const since = new Date(Date.now() - 24 * 60 * 60 * 1000);
  return ProjectModel.countDocuments({
    createdByUserId: new Types.ObjectId(userId),
    createdAt: { $gte: since },
    $or: [{ createdBySystem: true }, { createdByManualButton: true }],
  }).exec();
}

/**
 * Writes the decision trace onto a record AFTER the enqueue, so the ENQUEUE
 * step is itself part of it.
 *
 * BEST-EFFORT: by this point the generation is queued and the credits are
 * committed. Losing a debug artifact must never turn a successful, paid request
 * into an error the caller retries — which would pay again.
 */
export async function persistGenerationTrace(
  modelId: string,
  trace: ModelGenerationTrace
): Promise<void> {
  try {
    await ProjectModel.updateOne(
      { _id: new Types.ObjectId(modelId) },
      { $set: { generationTrace: trace } }
    ).exec();
  } catch {
    // Swallowed deliberately — see the doc comment.
  }
}

/** Widens the selector's trace into the loose shape the Mixed sub-doc stores,
 * so a counter added later is persisted rather than silently stripped. */
export function toStoredSelection(trace: object): Record<string, unknown> {
  return { ...trace } as Record<string, unknown>;
}

function isDuplicateKeyError(err: unknown): boolean {
  return typeof err === 'object' && err !== null && (err as { code?: number }).code === 11000;
}

